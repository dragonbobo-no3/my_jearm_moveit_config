static bool terminal(const struct je2_client *c)
{ return c->phase == JE2_CLIENT_RETIRED || c->phase == JE2_CLIENT_FAULT || c->phase == JE2_CLIENT_CLOSED; }
static int fail(struct je2_client *c)
{ c->phase = JE2_CLIENT_FAULT; return -1; }
void je2_client_retire(struct je2_client *c)
{ if (!terminal(c)) c->phase = JE2_CLIENT_RETIRED; }
void je2_client_send_failed(struct je2_client *c) { (void)fail(c); }
int je2_client_init(struct je2_client *c)
{
    if (!c) return -1;
    memset(c, 0, sizeof(*c));
    unsigned char random[16];
    if (getrandom(random, sizeof(random), GRND_NONBLOCK) != (ssize_t)sizeof(random)) return fail(c);
    const char hex[] = "0123456789abcdef";
    for (int i = 0; i < 16; ++i) {
        c->client[2 * i] = hex[random[i] >> 4]; c->client[2 * i + 1] = hex[random[i] & 15];
    }
    return 0; /* Server boot is learned, NEVER generated by this client. */
}
static bool clock_valid(struct je2_client *c, double now)
{
    if (!isfinite(now) || now < c->now) { fail(c); return false; }
    c->now = now; return true;
}
int je2_client_tick(struct je2_client *c, double now)
{
    if (terminal(c) || !clock_valid(c, now)) return -1;
    if (c->seen && now - c->received_at > .15) return fail(c);
    if ((c->phase == JE2_CLIENT_CLAIMING || c->phase == JE2_CLIENT_SWITCHING ||
         c->phase == JE2_CLIENT_HOLDING) && now > c->deadline) return fail(c);
    if ((c->phase == JE2_CLIENT_DRAINING || c->phase == JE2_CLIENT_CLOSING) &&
        now > c->close_deadline) return fail(c);
    if ((c->phase == JE2_CLIENT_ACTIVE || c->phase == JE2_CLIENT_DRAINING || c->phase == JE2_CLIENT_CLOSING) &&
        c->acknowledged < c->wire_sequence &&
        now > c->deadline) return fail(c);
    return 0;
}
static struct json_object *field(struct json_object *o, const char *key)
{ struct json_object *v = NULL; return o && json_object_object_get_ex(o, key, &v) ? v : NULL; }
static bool boolean(struct json_object *o, const char *key, bool expected)
{
    struct json_object *v = field(o, key);
    return v && json_object_get_type(v) == json_type_boolean && !!json_object_get_boolean(v) == expected;
}
static bool hex_token(const char *s)
{ return s && strlen(s) == 32 && strspn(s, "0123456789abcdef") == 32; }
/* Read integers from the original spelling, avoiding json-c's saturation of
 * out-of-range JSON integers. Exactly one unescaped key occurrence is allowed. */
static bool uint_field(const char *body, const char *key, uint64_t *out)
{
    char token[80]; snprintf(token, sizeof(token), "\"%s\"", key);
    const char *p = strstr(body, token);
    if (!p || strstr(p + strlen(token), token)) return false;
    p += strlen(token); while (isspace((unsigned char)*p)) ++p;
    if (*p++ != ':') return false;
    while (isspace((unsigned char)*p)) ++p;
    if (*p < '0' || *p > '9' || (*p == '0' && isdigit((unsigned char)p[1]))) return false;
    uint64_t value = 0;
    do {
        unsigned digit = (unsigned)(*p++ - '0');
        if (value > (UINT64_MAX - digit) / 10) return false;
        value = value * 10 + digit;
    } while (*p >= '0' && *p <= '9');
    while (isspace((unsigned char)*p)) ++p;
    if (*p != ',' && *p != '}') return false;
    *out = value; return true;
}
static bool unique_keys(const char *body)
{
    const char *keys[] = {"implementation", "experimental", "loopback_only", "session_transport_enabled",
        "session_boot", "session_client", "snapshot_feedback", "valid", "Joint",
        "automatic_priority_ready", "writer_exit_verified", "pc_reclaim_supported"};
    for (size_t i = 0; i < sizeof(keys) / sizeof(keys[0]); ++i) {
        char token[80]; snprintf(token, sizeof(token), "\"%s\"", keys[i]);
        const char *p = strstr(body, token);
        if (!p || strstr(p + strlen(token), token)) return false;
    }
    return true;
}
int je2_client_observe(struct je2_client *c, const char *frame, size_t size, double now)
{
    if (je2_client_tick(c, now)) return -1;
    if (!frame || size <= 6 || size >= MK2_FRAME_MAX || memcmp(frame, "Owner ", 6) ||
        memchr(frame, '\0', size) || memchr(frame, '\\', size)) return fail(c);
    char body[MK2_FRAME_MAX]; memcpy(body, frame + 6, size - 6); body[size - 6] = '\0';
    struct json_tokener *tok = json_tokener_new_ex(8);
    if (!tok) return fail(c);
    json_tokener_set_flags(tok, JSON_TOKENER_STRICT);
    struct json_object *o = json_tokener_parse_ex(tok, body, (int)size - 6);
    size_t end = json_tokener_get_parse_end(tok);
    while (end < size - 6 && isspace((unsigned char)body[end])) ++end;
    bool ok = o && json_object_get_type(o) == json_type_object &&
        json_tokener_get_error(tok) == json_tokener_success && end == size - 6 && unique_keys(body);
    json_tokener_free(tok);
    const char *keys[] = {"snapshot_version", "snapshot_sequence", "generation", "session_generation",
        "session_last_sequence", "owner", "snapshot_phase", "snapshot_fault", "snapshot_sdk_error",
        "PowerState", "MoveState", "DriverError", "MoveError"};
    uint64_t values[13] = {0};
    for (size_t i = 0; ok && i < 13; ++i) ok = uint_field(body, keys[i], &values[i]);
    struct json_object *b = o ? field(o, "session_boot") : NULL;
    struct json_object *id = o ? field(o, "session_client") : NULL;
    struct json_object *f = o ? field(o, "snapshot_feedback") : NULL;
    struct json_object *q = f ? field(f, "Joint") : NULL;
    struct json_object *impl = o ? field(o, "implementation") : NULL;
    for (size_t i = 0; ok && i < 13; ++i) {
        struct json_object *v = field(i < 9 ? o : f, keys[i]);
        ok = v && json_object_get_type(v) == json_type_int;
    }
    const char *boot = b && json_object_get_type(b) == json_type_string ? json_object_get_string(b) : NULL;
    const char *client = id && json_object_get_type(id) == json_type_string ? json_object_get_string(id) : NULL;
    ok = ok && impl && json_object_get_type(impl) == json_type_string &&
        !strcmp(json_object_get_string(impl), "JEServer_v2") && hex_token(boot) &&
        client && (!*client || hex_token(client)) && boolean(o, "experimental", true) &&
        boolean(o, "loopback_only", true) && boolean(o, "session_transport_enabled", true) &&
        boolean(o, "automatic_priority_ready", false) && boolean(o, "writer_exit_verified", false) &&
        boolean(o, "pc_reclaim_supported", false) && values[0] == 1 && values[1] > 0 && values[2] > 0 &&
        values[5] <= JE2_FAULT && values[6] <= MK2_RELEASING && !values[7] && !values[8] &&
        f && json_object_get_type(f) == json_type_object && boolean(f, "valid", true) &&
        values[9] == 1 && values[10] <= INT_MAX && values[10] != 7 && !values[11] && !values[12] &&
        q && json_object_get_type(q) == json_type_array && json_object_array_length(q) == MK2_AXES;
    double joints[MK2_AXES] = {0};
    for (int i = 0; ok && i < MK2_AXES; ++i) {
        struct json_object *v = json_object_array_get_idx(q, (size_t)i);
        ok = v && (json_object_get_type(v) == json_type_int || json_object_get_type(v) == json_type_double);
        if (ok) { joints[i] = json_object_get_double(v); ok = isfinite(joints[i]); }
    }
    bool release_supported = false;
    struct json_object *release_seq = field(o, "session_release_sequence"), *release_phase = field(o, "session_release_phase");
    if (ok && (release_seq || release_phase)) {
        uint64_t rs = 0, rp = 0;
        release_supported = release_seq && release_phase && json_object_get_type(release_seq) == json_type_int &&
            json_object_get_type(release_phase) == json_type_int &&
            uint_field(body, "session_release_sequence", &rs) && uint_field(body, "session_release_phase", &rp) && rp <= 2;
        ok = release_supported;
    }
    int result = -1;
    if (!ok) { fail(c); goto done; }
    if (c->seen && strcmp(boot, c->boot)) { je2_client_retire(c); goto done; }
    if (c->seen && values[1] <= c->observation) { result = 1; goto done; }
    if (values[5] == JE2_FAULT) { fail(c); goto done; }
    if (c->phase == JE2_CLIENT_OBSERVING) {
        memcpy(c->boot, boot, 33); c->generation = values[2];
    } else if (c->phase == JE2_CLIENT_CLAIMING) {
        if (values[2] == c->generation && values[5] != JE2_AVAILABLE && values[5] != JE2_PENDANT) {
            je2_client_retire(c); goto done;
        }
        if (values[2] != c->generation) {
            if (values[2] != c->generation + 1 || values[3] != values[2] || strcmp(client, c->client) ||
                values[5] != JE2_AVAILABLE || values[6] != MK2_READY || values[4] != 0) {
                je2_client_retire(c); goto done;
            }
            c->generation = values[2]; c->phase = JE2_CLIENT_BOUND;
        }
    } else if (c->phase == JE2_CLIENT_CLOSING) {
        uint64_t release_sequence = 0, release_phase = 0;
        struct json_object *rs = field(o, "session_release_sequence"), *rp = field(o, "session_release_phase");
        if (!rs || !rp || json_object_get_type(rs) != json_type_int || json_object_get_type(rp) != json_type_int ||
            !uint_field(body, "session_release_sequence", &release_sequence) ||
            !uint_field(body, "session_release_phase", &release_phase) || release_phase > 2) {
            fail(c); goto done;
        }
        if (values[3] != c->generation || strcmp(client, c->client)) { je2_client_retire(c); goto done; }
        if (values[4] > c->wire_sequence || values[4] < c->acknowledged) { fail(c); goto done; }
        if (values[2] == c->generation) {
            /* Owner publication preceding receipt of our Release. No ACK or
             * deadline extension; no repeated Release while awaiting it. */
            if (values[5] != JE2_PC || values[6] != MK2_ACTIVE ||
                values[4] != c->wire_sequence - 1 || release_sequence || release_phase) {
                fail(c); goto done;
            }
        } else {
            if (c->generation == UINT64_MAX || values[2] != c->generation + 1 ||
                release_sequence != c->wire_sequence || values[4] != c->wire_sequence || !release_phase) {
                je2_client_retire(c); goto done;
            }
            const bool pending = release_phase == 1 &&
                ((values[5] == JE2_YIELDING && values[6] == MK2_RELEASING) ||
                 (values[5] == JE2_EXIT_BARRIER && values[6] == MK2_READY));
            const bool closed = release_phase == 2 && values[5] == JE2_PENDANT &&
                values[6] == MK2_READY && values[10] == 0;
            if (!pending && !closed) { fail(c); goto done; }
            c->acknowledged = values[4];
            if (closed) c->phase = JE2_CLIENT_CLOSED;
        }
    } else {
        if (values[2] != c->generation || values[3] != c->generation || strcmp(client, c->client) ||
            (values[5] != JE2_AVAILABLE && values[5] != JE2_PC)) { je2_client_retire(c); goto done; }
        if (values[4] > c->wire_sequence || values[4] < c->acknowledged) { fail(c); goto done; }
        bool ready = values[5] == JE2_AVAILABLE && values[6] == MK2_READY && values[4] == 0;
        bool waiting = values[5] == JE2_PC && values[6] == MK2_WAIT_FIRST && values[4] == 1;
        bool active = values[5] == JE2_PC && values[6] == MK2_ACTIVE && values[4] >= 2;
        if ((c->phase == JE2_CLIENT_BOUND && !ready) ||
            (c->phase == JE2_CLIENT_SWITCHING && !ready && !waiting) ||
            (c->phase == JE2_CLIENT_HOLD_READY && !waiting) ||
            (c->phase == JE2_CLIENT_HOLDING && !waiting && !active) ||
            ((c->phase == JE2_CLIENT_ACTIVE || c->phase == JE2_CLIENT_DRAINING) && !active)) { fail(c); goto done; }
        if (c->phase == JE2_CLIENT_SWITCHING && values[4] == 1 && values[5] == JE2_PC && values[6] == MK2_WAIT_FIRST)
            c->phase = JE2_CLIENT_HOLD_READY;
        if (c->phase == JE2_CLIENT_HOLDING && values[4] == 2 && values[5] == JE2_PC && values[6] == MK2_ACTIVE)
            c->phase = JE2_CLIENT_ACTIVE;
        c->acknowledged = values[4];
    }
    c->owner = (int)values[5]; c->native_phase = (int)values[6];
    c->observation = values[1]; c->received_at = now; c->seen = true;
    c->release_supported = release_supported;
    memcpy(c->joint, joints, sizeof(joints)); result = 0;
done:
    if (o) json_object_put(o);
    return result;
}
static int output(struct je2_client *c, char *out, size_t size, const char *payload)
{
    if (!out || !size) return fail(c);
    out[0] = '\0';
    if (payload && c->wire_sequence == UINT64_MAX) return fail(c);
    int n = payload ? snprintf(out, size, "JE2F1 %s %llu %s %llu %s", c->boot,
        (unsigned long long)c->generation, c->client, (unsigned long long)(c->wire_sequence + 1), payload) :
        snprintf(out, size, "JE2C1 %s %llu %s", c->boot, (unsigned long long)c->generation, c->client);
    if (n < 0 || (size_t)n >= size || n >= MK2_FRAME_MAX) { out[0] = '\0'; return fail(c); }
    if (payload) ++c->wire_sequence;
    return n;
}
int je2_client_claim(struct je2_client *c, double now, char *out, size_t size)
{
    if (out && size) out[0] = '\0';
    if (c->phase == JE2_CLIENT_CLAIMING) {
        if (je2_client_tick(c, now)) return -1;
        if (now < c->next_claim) return 0;
        int n = output(c, out, size, NULL);
        if (n > 0) c->next_claim = now + .02;
        return n;
    }
    if (je2_client_tick(c, now) || !c->seen || c->phase != JE2_CLIENT_OBSERVING ||
        (c->owner != JE2_AVAILABLE && c->owner != JE2_PENDANT) || c->native_phase != MK2_READY ||
        c->generation == UINT64_MAX) return -1;
    int n = output(c, out, size, NULL);
    if (n > 0) { c->phase = JE2_CLIENT_CLAIMING; c->deadline = now + .5; c->next_claim = now + .02; }
    return n;
}
int je2_client_switch(struct je2_client *c, double now, char *out, size_t size)
{
    if (out && size) out[0] = '\0';
    if (je2_client_tick(c, now) || c->phase != JE2_CLIENT_BOUND) return -1;
    int n = output(c, out, size, "Switch {\"Switch\":true}");
    if (n > 0) { c->phase = JE2_CLIENT_SWITCHING; c->deadline = now + .5; }
    return n;
}
int je2_client_hold(struct je2_client *c, double now, double dt, char *out, size_t size)
{
    if (out && size) out[0] = '\0';
    if (je2_client_tick(c, now) || c->phase != JE2_CLIENT_HOLD_READY) return -1;
    if (!isfinite(dt) || dt < .005 || dt > .05) return fail(c);
    char body[1024];
    int n = snprintf(body, sizeof(body), "Joint {\"Robot0\":{\"time\":%.17g,\"joint\":[%.17g,%.17g,%.17g,%.17g,%.17g,%.17g,%.17g]}}",
        dt, c->joint[0], c->joint[1], c->joint[2], c->joint[3], c->joint[4], c->joint[5], c->joint[6]);
    if (n < 0 || (size_t)n >= sizeof(body)) return fail(c);
    n = output(c, out, size, body);
    if (n > 0) {
        c->phase = JE2_CLIENT_HOLDING; c->deadline = now + .5;
        c->first_target_at = now; c->first_data_time = c->last_data_time = dt;
        memcpy(c->first_target, c->joint, sizeof(c->first_target));
    }
    return n;
}
int je2_client_get_lease(const struct je2_client *c, struct je2_client_lease *lease)
{
    if (!lease) return -1;
    memset(lease, 0, sizeof(*lease));
    if (c->phase != JE2_CLIENT_ACTIVE) return -1;
    memcpy(lease->boot, c->boot, sizeof(lease->boot));
    memcpy(lease->client, c->client, sizeof(lease->client));
    lease->generation = c->generation;
    return 0;
}
int je2_client_close(struct je2_client *c, const struct je2_client_lease *lease, double now, char *out, size_t size)
{
    if (out && size) out[0] = '\0';
    /* Same old-callback fence as target, before clocks or any mutation. */
    if (!lease || lease->generation != c->generation ||
        memcmp(lease->boot, c->boot, sizeof(lease->boot)) ||
        memcmp(lease->client, c->client, sizeof(lease->client))) return -1;
    if (c->phase == JE2_CLIENT_CLOSED) return 0; /* historical receipt, no traffic */
    if (je2_client_tick(c, now)) return -1;
    if ((c->phase == JE2_CLIENT_ACTIVE || c->phase == JE2_CLIENT_DRAINING) && !c->release_supported) return fail(c);
    if (c->phase == JE2_CLIENT_ACTIVE) {
        if (c->generation == UINT64_MAX) return fail(c);
        c->phase = JE2_CLIENT_DRAINING;
        c->close_deadline = now + .5;
    }
    if (c->phase == JE2_CLIENT_CLOSING) return 0;
    if (c->phase != JE2_CLIENT_DRAINING) return -1;
    if (c->acknowledged != c->wire_sequence) return 0;
    const int n = output(c, out, size, "Release {\"Release\":true}");
    if (n > 0) { c->phase = JE2_CLIENT_CLOSING; c->deadline = now + .1; }
    return n;
}
int je2_client_target(struct je2_client *c, const struct je2_client_lease *lease, double now,
                      double data_time, const double joint[MK2_AXES], char *out, size_t size)
{
    if (out && size) out[0] = '\0';
    /* Retired callbacks must never mutate the new session, even with bad data
     * or clocks. The caller must separately tick the live session watchdog. */
    if (!lease || lease->generation != c->generation ||
        memcmp(lease->boot, c->boot, sizeof(lease->boot)) ||
        memcmp(lease->client, c->client, sizeof(lease->client))) return -1;
    if (je2_client_tick(c, now) || c->phase != JE2_CLIENT_ACTIVE) return -1;
    if (!joint || !isfinite(data_time)) return fail(c);
    double dt = data_time - c->last_data_time;
    if (!isfinite(dt) || dt < .005 || dt > .05 ||
        fabs((data_time - c->first_data_time) - (now - c->first_target_at)) > .05) return fail(c);
    for (int i = 0; i < MK2_AXES; ++i) if (!isfinite(joint[i])) return fail(c);
    if (c->acknowledged != c->wire_sequence) return 0;
    char body[1024];
    int n = snprintf(body, sizeof(body), "Joint {\"Robot0\":{\"time\":%.17g,\"joint\":[%.17g,%.17g,%.17g,%.17g,%.17g,%.17g,%.17g]}}",
        data_time, joint[0], joint[1], joint[2], joint[3], joint[4], joint[5], joint[6]);
    if (n < 0 || (size_t)n >= sizeof(body)) return fail(c);
    n = output(c, out, size, body);
    if (n > 0) { c->last_data_time = data_time; c->deadline = now + .1; }
    return n;
}